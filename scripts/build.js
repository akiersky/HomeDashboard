#!/usr/bin/env node
'use strict';

/**
 * Packages Family Dashboard:
 * 1. Assembles modular source files (src/*.js) into js/bundle.js (standalone/browser).
 * 2. Compiles a single-file HACS Lovelace plugin (family-dashboard.js).
 * Zero external dependencies.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'src');
const read = (...p) => fs.readFileSync(path.join(ROOT, ...p), 'utf8');

const SOURCE_FILES = [
  'helpers.js',
  'weather.js',
  'night-mode.js',
  'state-manager.js',
  'kiosk-mode.js',
  'ha-session.js',
  'ha-websocket.js',
  'parent-tasks.js',
  'mission-ledger.js',
  'ha-lists.js',
  'calendar-feed.js',
  'calendar-module.js',
  'chores-module.js',
  'meals-module.js',
  'parent-gate.js',
  'chores-admin.js',
  'photo-frame.js',
  'doorbell.js',
  'renderer.js',
  'app.js'
];

function compileBundle() {
  const parts = SOURCE_FILES.map(f => {
    const filePath = path.join(SRC_DIR, f);
    if (!fs.existsSync(filePath)) throw new Error(`Missing source file: ${filePath}`);
    return fs.readFileSync(filePath, 'utf8').trim();
  });

  return `/* ==========================================================================
   FAMILY DASHBOARD - APPLICATION BUNDLE
   Auto-generated by scripts/build.js from src/. Do not edit by hand.
   ========================================================================== */

(function() {
  'use strict';

${parts.join('\n\n')}
})();
`;
}

function build() {
  // 1. Build js/bundle.js from src/
  const bundleJs = compileBundle();
  const bundlePath = path.join(ROOT, 'js', 'bundle.js');
  fs.writeFileSync(bundlePath, bundleJs, 'utf8');
  console.log(`Compiled ${bundlePath} (${(Buffer.byteLength(bundleJs) / 1024).toFixed(1)} KB from ${SOURCE_FILES.length} source files)`);

  // 2. Build family-dashboard.js (HACS custom card)
  const indexHtml = read('index.html');
  const stylesCss = read('styles.css');
  const seed = JSON.stringify(JSON.parse(read('data', 'dashboard-data.json')));

  const safe = (code) => code.replace(/<\/script/gi, '<\\/script');
  const doc = indexHtml
    .replace(/<link[^>]*href="styles\.css[^"]*"[^>]*>/, () => `<style>${stylesCss}</style>`)
    .replace(/<script src="config\.js[^"]*"><\/script>\s*/, '')
    .replace(/<script src="js\/bundle\.js[^"]*"><\/script>/, () => `<script>window.__FD_SEED__=${safe(seed)};</script><script>${safe(bundleJs)}</script>`);

  if (/src="js\/bundle\.js|href="styles\.css|src="config\.js/.test(doc)) {
    console.error('index.html markup changed: could not inline styles/bundle/config');
    process.exit(1);
  }

  const ascii = (js) => js.replace(/[\u007f-\uffff]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));

  const output = `/**
 * Family Dashboard - Home Assistant Lovelace card, distributed via HACS.
 * Auto-generated by scripts/build.js. Do not edit by hand.
 */
(function() {
  'use strict';

  const DASHBOARD_DOC = ${ascii(JSON.stringify(doc))};

  class FamilyDashboardCard extends HTMLElement {
    set hass(hass) {
      this._hass = hass;
      this._pushConnection();
    }

    setConfig(config) {
      this._config = config || {};
    }

    connectedCallback() {
      if (this._frame) return;
      this.style.display = 'block';
      this.style.height = '100%';
      const frame = this._frame = document.createElement('iframe');
      frame.style.cssText = 'display:block;width:100%;height:100%;min-height:100vh;border:0;';
      frame.addEventListener('load', () => this._pushConnection());
      frame.srcdoc = DASHBOARD_DOC;
      this.appendChild(frame);
    }

    // The app already finds window.parent.hassConnection; this covers hosts that only hand over hass.connection.
    _pushConnection() {
      const win = this._frame && this._frame.contentWindow;
      if (win && win.haWS && this._hass && this._hass.connection) win.haWS.setNativeConnection(this._hass.connection);
    }

    getCardSize() {
      return 12;
    }
  }

  if (!customElements.get('family-dashboard')) {
    customElements.define('family-dashboard', FamilyDashboardCard);
  }

  window.customCards = window.customCards || [];
  if (!window.customCards.some(c => c.type === 'family-dashboard')) {
    window.customCards.push({
      type: 'family-dashboard',
      name: 'Family Dashboard',
      description: 'Wall-mounted family display: calendar, chores, meals, weather and photo screensaver'
    });
  }
})();
`;

  const out = path.join(ROOT, 'family-dashboard.js');
  fs.writeFileSync(out, output, 'utf8');
  console.log(`Built ${out} (${(Buffer.byteLength(output) / 1024).toFixed(1)} KB)`);
}

module.exports = { compileBundle, build, SOURCE_FILES };

if (require.main === module) {
  build();
}
